"""Writes docs/RESULTS.md and docs/BENCHMARKS.md from the files in results/.

Every figure in the README and the reports is read from a results file written
by a `make` target, and each section names the command that produced it.
"""

from __future__ import annotations

import json
import os
import platform
import subprocess
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"
DOCS = ROOT / "docs"


def load(name: str) -> Any:
    path = RESULTS / name
    return json.loads(path.read_text()) if path.exists() else None


def machine() -> str:
    try:
        cpu = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout
    except OSError:
        cpu = ""
    cores = os.cpu_count()
    return f"{cpu.strip() or platform.processor()}, {cores} cores, {platform.system()} {platform.release()}"


def money(x: float) -> str:
    return f"{'-' if x < 0 else ''}${abs(x):,.2f}"


def benchmarks() -> str:
    lines = ["# Benchmarks", "", f"Machine: {machine()}.", ""]
    engine = load("engine_bench.json")
    if engine:
        lines += ["## Matching engine (`make bench`)", "", "| Benchmark | Result |", "| --- | --- |"]
        for b in engine["benchmarks"]:
            if "orders_per_sec" in b:
                lines.append(f"| Throughput, single thread | {b['orders_per_sec'] / 1e6:.1f}M orders per second |")
                lines.append(f"| Heap allocations per order | {b['allocs_per_order']:.0f} |")
            if "p99_ns" in b:
                lines.append(f"| Latency per operation | p50 {b['p50_ns']:.0f} ns, p99 {b['p99_ns']:.0f} ns, "
                             f"p99.9 {b['p999_ns']:.0f} ns |")  # fmt: skip
        lines += ["", "Latency samples include roughly 20 ns of steady-clock overhead per call.", ""]
    feed = load("feed_bench.json")
    if feed:
        r, c = feed["replay"], feed["capture"]
        lines += [
            "## Multicast feed on loopback (`make bench-feed`)",
            "",
            "| Measure | Result |",
            "| --- | --- |",
            f"| Book events published | {r['events_published']:,} in {r['packets']:,} datagrams |",
            f"| Publish rate | {r['events_per_sec'] / 1e6:.2f}M events per second |",
            f"| Messages captured | {c['messages']:,} |",
            f"| Sequence gaps | {c['gaps']} ({c['lost_messages']} messages lost) |",
            f"| One-way latency per packet | p50 {c['latency_p50_ns'] / 1e3:.1f} µs, "
            f"p99 {c['latency_p99_ns'] / 1e3:.1f} µs |",
            "",
        ]
    return "\n".join(lines)


def results() -> str:
    lines = ["# Results", "", f"Generated by `make results` on {machine()}.", ""]
    manifest = json.loads((ROOT / "data/synthetic/manifest.json").read_text())
    lines += [
        "## Data (`make data`)",
        "",
        f"{len(manifest['files'])} symbol-days of synthetic order flow in LOBSTER format: "
        f"{manifest['total_messages']:,} order book events across {len(manifest['profiles'])} symbols.",
        "",
    ]
    meta_path = ROOT / "data/headlines/headlines.meta.json"
    if meta_path.exists():
        meta = json.loads(meta_path.read_text())
        line = f"{meta['rows']:,} headlines scored by FinBERT ({meta['source']} source)"
        if "finbert_sign_agreement" in meta:
            line += f"; FinBERT's sign agrees with the human label on {100 * meta['finbert_sign_agreement']:.1f}%"
        lines += [line + " of bullish and bearish headlines (`make headlines`).", ""]

    forecast = load("forecast.json")
    if forecast:
        lines += ["## Forecasts (`make forecast`)", "",
                  "Out-of-sample Spearman information coefficient, averaged over purged walk-forward folds.", "",
                  "| Horizon | LightGBM | Micro-price baseline | Directional hit rate |",
                  "| --- | --- | --- | --- |"]  # fmt: skip
        for h in (1, 10, 60):
            folds = forecast[f"fwd{h}"]["folds"]
            ic = sum(f["lightgbm"]["ic"] for f in folds) / len(folds)
            base = sum(f["microprice_baseline"]["ic"] for f in folds) / len(folds)
            hit = sum(f["lightgbm"]["hit_rate"] for f in folds) / len(folds)
            lines.append(f"| {h} s | {ic:.3f} | {base:.3f} | {100 * hit:.1f}% |")
        lines.append("")

    sweep = load("sweep.json")
    holdout = load("holdout.json")
    if sweep and holdout:
        sel = holdout["selection"]
        lines += [
            "## Parameter sweep (`make sweep`)",
            "",
            f"{sweep['parameter_sets']:,} parameter sets, {sweep['backtests']:,} backtests on Spark in "
            f"{sweep['seconds'] / 60:.0f} minutes. The selected set has a per-minute Sharpe ratio of "
            f"{sel['raw_sharpe_1min']:.3f} against an expected maximum of {sel['expected_max_sharpe_1min']:.3f} "
            f"for {int(sel['trials']):,} unskilled trials; deflated Sharpe ratio {sel['deflated_sharpe']:.3f}.",
            "",
        ]
    if holdout:
        lines += ["## Held-out days (`make evaluate`)", "",
                  f"Days {', '.join(holdout['holdout_days'])}, all symbols, parameters fixed before these days were used.",
                  "",
                  "| Strategy | P&L | Sharpe (annualized from 1-min P&L) | 10 s markout (ticks) | Fills | Max drawdown |",
                  "| --- | --- | --- | --- | --- | --- |"]  # fmt: skip
        for name, s in holdout["summary"].items():
            lines.append(
                f"| {name} | {money(s['pnl_usd'])} | {s['sharpe']:.2f} | {s['markout_10s']:.3f} | "
                f"{int(s['fills']):,} | {money(s['max_drawdown_usd'])} |"
            )
        lines += ["", f"Sharpe change from baseline to signal: {100 * holdout['sharpe_lift']:+.0f}%.", ""]
        lines += ["Annualizing intraday Sharpe ratios overstates what a full year would show; the figures are "
                  "for comparing strategies on the same days, not as a forecast.", ""]  # fmt: skip
    analysis = load("analysis/analysis.json")
    if analysis:
        lines += ["## Adverse selection (`make analysis`, R)", "", "| Strategy | Horizon | Markout (ticks/share) |",
                  "| --- | --- | --- |"]  # fmt: skip
        for row in analysis["markouts"]:
            lines.append(f"| {row['variant']} | {row['horizon_s']} s | {row['markout']:+.3f} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "BENCHMARKS.md").write_text(benchmarks() + "\n")
    (DOCS / "RESULTS.md").write_text(results() + "\n")
    print((DOCS / "RESULTS.md").read_text())


if __name__ == "__main__":
    main()
